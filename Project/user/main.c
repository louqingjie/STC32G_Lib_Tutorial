// 因此，在这里我们只能声明全局变量，或者在函数开头声明局部变量，不能在函数中间声明变量。
// 但是，这不是一种好的编程习惯，尤其是在函数较长的情况下，变量的作用域过大，容易导致代码混乱和错误。
// 因此，在这里我建议你在函数开头声明所有需要使用的变量，并且尽量减少变量的作用域避免在函数中间声明变量。
// 如果你在编译时出现了error C25: syntax error near 'int'的错误提示，
// 那么很可能就是你在函数中间声明了变量，或者在函数中使用了C99标准中的一些特性，例如for循环中的变量声明等。
// 值得一提的是，要定位错误出现的位置，你不能看error C25中的25这个数字，因为它并不代表行号，而是代表编译器内部的错误代码。
// 你需要看的是文件名后紧跟的用小括号()括起来的数字，这个数字才是行号，例如main.c(50)中的50就是行号，表示错误出现在main.c文件的第50行。

uint8 input_level;
uint16 adc_value;
const char uartData[20] = "Hello, UART!"; // 定义要发送的数据

void main()
{
    // ===============第一章 GPIO——通用输入输出===============

    // GPIO（General Purpose Input/Output）是单片机中最基本的外设之一，
    // 用于实现数字信号的输入和输出。通过GPIO，我们可以控制LED灯的亮灭，读取按键的状态，或者与其他外设进行通信。

    // 第一节 GPIO初始化

    // 初始化P20为输出，初始电平为高，模式为无上下拉
    gpio_init(IO_P20, GPO, GPIO_HIGH, GPIO_NO_PULL);
    // 初始化P21为输入，初始电平为低，模式为上拉输入
    gpio_init(IO_P21, GPI, GPIO_LOW, GPI_PULL_UP);

    // 函数第二个参数说明：
    // 输入
    // GPI_IMPEDANCE    高阻输入
    // GPI_FLOATING_IN  浮空输入模式
    // GPI_PULL_DOWN    下拉输入
    // GPI_PULL_UP      上拉输入

    // 输出
    //  GPO_PUSH_PULL    通用推挽输出模式
    //  GPO_OPEN_DTAIN   通用开漏输出模式

    // 双向GPIO，既可以输入也可以输出
    // GPIO_NO_PULL     GPIO无上下拉

    // 第二节 GPIO输出

    // 1.2.1 GPIO输出函数

    gpio_set_level(IO_P20, GPIO_LOW);  // 输出P20为低电平
    gpio_set_level(IO_P20, GPIO_HIGH); // 输出P20为高电平

    // 1.2.2 GPIO输出宏

    // 输出P20为低电平
    gpio_low(IO_P20);
    // 输出P20为高电平
    gpio_high(IO_P20);

    // 第三节 GPIO输入

    // 1.3.1 GPIO输入函数

    input_level = gpio_get_level(IO_P21); // 读取P21的输入电平
    // 补充说明：
    // uint8即unsigned char，表示8位无符号整数，取值范围为0~255
    // uint16即unsigned short，表示16位无符号整数，取值范围为0~65535
    // uint32即unsigned int，表示32位无符号整数，取值范围为0~4294967295
    // int8即signed char，表示8位有符号整数，取值范围为-128~127
    // int16即signed short，表示16位有符号整数，取值范围为-32768~32767
    // int32即signed int，表示32位有符号整数，取值范围为-2147483648~2147483647

    // ===============第二章 PWM——脉宽调制===============

    // PWM（Pulse Width Modulation）是一种通过改变信号的占空比来控制功率输出的技术。
    // 它广泛应用于电机控制、LED调光等领域。

    // 第一节 PWM初始化

    // 初始化PWM0，频率为1kHz，占空比为50%
    pwm_init(PWMB_CH3_P22, 1000, 5000);
    pwm_init(PWMA_CH2N_P23, 1000, 5000);
    // 函数第一个参数说明：
    // PWMB_CH3_P22表示PWM通道3，输出引脚为P22
    // PWMA_CH2N_P23表示PWM通道2的负极，输出引脚为P23
    // 函数第二个参数说明：
    // 频率单位为Hz，例如1000表示1kHz
    // 函数第三个参数说明：
    // 占空比单位为万分比，例如5000表示占空比为50%

    // 第二节 PWM占空比设置

    // 设置PWM0占空比为75%
    pwm_set_duty(PWMB_CH3_P22, 7500);

    // 第三节 PWM频率设置
    pwm_set_freq(PWMB_CH3_P22, 2000, 5000); // 设置PWM0频率为2kHz，占空比为50%

    // ==============第三章 ADC——模数转换===============
    // ADC（Analog to Digital Converter）是一种将模拟信号转换为数字信号的设备。
    // 通过ADC，我们可以读取传感器的模拟输出，并将其转换为数字值进行处理。

    // 第一节 ADC初始化
    adc_init(ADC_CH0_P10, ADC_12BIT); // 初始化ADC通道0，P10针脚输入，12位精度
    // 函数第一个参数说明：
    // ADC_CH0_P10表示ADC通道0，输入引脚为P10，下面是其他通道：
    // ADC_CH0_P10,
    // ADC_CH1_P11,
    // ADC_CH2_P12,
    // ADC_CH3_P13,
    // ADC_CH4_P14,
    // ADC_CH5_P15,
    // ADC_CH6_P16,
    // ADC_CH7_P17,
    // ADC_CH8_P00,
    // ADC_CH9_P01,
    // ADC_CH10_P02,
    // ADC_CH11_P03,
    // ADC_CH12_P04,
    // ADC_CH13_P05,
    // ADC_CH14_P06,
    // ADC_CH15_POWR = 0x0f, // 内部AD 1.19V

    // 函数第二个参数说明：
    // ADC_12BIT表示12位精度，下面是其他精度选项：
    // ADC_12BIT,       // 12位分辨率，ADC转换结果为0~4095
    // ADC_11BIT,       // 11位分辨率，ADC转换结果为0~2047
    // ADC_10BIT,       // 10位分辨率，ADC转换结果为0~1023
    // ADC_9BIT,        // 9位分辨率，ADC转换结果为0~511
    // ADC_8BIT,        // 8位分辨率，ADC转换结果为0~255

    // 第二节 ADC转换

    adc_value = adc_convert(ADC_CH0_P10); // 读取ADC通道0的转换结果
    // 函数参数说明：
    // ADC_CH0_P10表示ADC通道0，输入引脚为P10
    // 函数返回值说明：
    // adc_value为ADC转换结果，数据类型为uint16，根据精度不同，取值范围不同，例如12位精度时，adc_value的取值范围为0~4095

    // 第三节 ADC平均滤波转换

    adc_value = adc_mean_filter_convert(ADC_CH0_P10, 10); // 读取ADC通道0的平均滤波转换结果，滤波次数为10
    // 函数参数说明：
    // ADC_CH0_P10表示ADC通道0，输入引脚为P10
    // 10表示滤波次数，即进行10次ADC转换，并取平均值作为最终结果
    // 函数返回值说明：
    // adc_mean_value为ADC平均滤波转换结果，数据类型为uint16，根据精度不同，取值范围不同，例如12位精度时，adc_mean_value的取值范围为0~4095

    // ==============第四章 UART——串口通信===============
    // UART（Universal Asynchronous Receiver/Transmitter）是一种常用的串行通信协议。
    // 通过UART，我们可以实现单片机与计算机、其他单片机或外设之间的通信。
    // UART通信通常使用TX（发送）和RX（接收）两条线进行数据传输。
    // UART通信的基本原理是通过设置波特率、数据位、停止位和校验位等参数来确保数据的正确传输。
    // 通过UART，我们可以发送和接收文本数据、二进制数据等，实现各种通信功能，例如调试信息输出、传感器数据传输等。
    // UART通信的常见应用包括：
    // 1. 调试输出：通过UART将调试信息发送到计算机，可以使用VOFA+等串口调试工具进行查看和分析
    // 2. 传感器数据传输：将传感器采集的数据通过UART发送到其他设备进行处理
    // 3. 外设通信：通过UART与其他外设进行通信，例如蓝牙模块、Wi-Fi模块等

    // 第一节 UART初始化

    uart_init(UART_1, 115200, UART1_TX_P31, UART1_RX_P30); // 初始化UART1，波特率为115200，TX引脚为P31，RX引脚为P30
    // 函数第一个参数说明：
    // UART_1表示串口1，以此类推，最高到UART_4，UART_RESERVE仅占位使用
    // 函数第二个参数说明：
    // 波特率，例如115200表示115200bps
    // 函数第三个参数说明：
    // TX引脚，例如UART1_TX_P31表示串口1的TX引脚为P31，下面是其他引脚选项：
    // UART1_RX_P30 = 0x0000 | IO_P30, UART1_TX_P31 = 0x0000 | IO_P31,		//只能使用同一行的RX和TX引脚号。不允许混用
    // UART1_RX_P36 = 0x0100 | IO_P36, UART1_TX_P37 = 0x0100 | IO_P37,
    // UART1_RX_P16 = 0x0200 | IO_P16, UART1_TX_P17 = 0x0200 | IO_P17,
    // UART1_RX_P43 = 0x0300 | IO_P43, UART1_TX_P44 = 0x0300 | IO_P44,
    // UART2_RX_P10 = 0x1000 | IO_P10, UART2_TX_P11 = 0x1000 | IO_P11,
    // UART2_RX_P46 = 0x1100 | IO_P46, UART2_TX_P47 = 0x1100 | IO_P47,
    // UART3_RX_P00 = 0x2000 | IO_P00, UART3_TX_P01 = 0x2000 | IO_P01,
    // UART3_RX_P50 = 0x2100 | IO_P50, UART3_TX_P51 = 0x2100 | IO_P51,
    // UART4_RX_P02 = 0x3000 | IO_P02, UART4_TX_P03 = 0x3000 | IO_P03,
    // UART4_RX_P52 = 0x3100 | IO_P52, UART4_TX_P53 = 0x3100 | IO_P53

    // 第二节 UART发送数据

    uart_write_string(UART_1, uartData);      // 通过UART1发送字符串数据

    // 第三节 UART接收数据

    // UART接收数据通常需要在中断服务程序中处理，此处略过

    // 主函数内的教学到此结束，接下来介绍中断相关内容
}

