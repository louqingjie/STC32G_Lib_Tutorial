// 通过中断，我们可以实现更高效的程序设计，例如响应按键输入、处理定时器事件等。
// 中断的基本原理是当某个事件发生时，单片机会暂停当前正在执行的程序，转而执行一个预先定义好的中断服务程序（ISR）
// 处理完中断事件后，再返回到被中断的程序继续执行。

